def _jd(arch: dict, company: str, city: str, seniority: str, salary: tuple[int, int]) -> str:
    duties = "\n".join(f"{i}. {d}" for i, d in enumerate(arch["duties"], 1))
    reqs = "\n".join(f"{i}. {r}" for i, r in enumerate(arch["requirements"], 1))
    bonus = "\n".join(f"{i}. {b}" for i, b in enumerate(arch["bonus"], 1))
    return (
        f"【岗位职责】\n{duties}\n\n"
        f"【任职要求】\n{reqs}\n\n"
        f"【加分项】\n{bonus}\n\n"
        f"工作地点：{city}｜经验要求：{seniority}｜"
        f"薪资范围：{salary[0]}K-{salary[1]}K×15 薪｜所属团队：{company}"
    )


def build_jobs() -> list[dict]:
    """生成 50 条：25 个原型，每个原型出「中级 + 高级」两条。"""
    jobs: list[dict] = []
    for i in range(len(ARCHETYPES) * len(LEVELS)):
        arch = ARCHETYPES[i % len(ARCHETYPES)]
        suffix, seniority, factor = LEVELS[i // len(ARCHETYPES)]
        # 公司按 7 步长错开，避免同一原型的两个职级落在同一家公司
        name, city, industry, tags = COMPANIES[(i * 7) % len(COMPANIES)]
        lo = int(round(arch["salary"][0] * factor))
        hi = int(round(arch["salary"][1] * factor))
        skills = list(arch["skills"])
        if suffix:  # 高级版追加两个进阶技能，制造技能缺口差异
            skills += ["架构设计", "技术选型与团队带教"]
        jobs.append(
            {
                "id": f"job_{i + 1:03d}",
                "title": arch["title"] + suffix,
                "company": name,
                "city": city,
                "salary_min": lo,
                "salary_max": hi,
                "seniority": seniority,
                "industry": industry,
                "tags": [*tags, f"{lo}K-{hi}K"],
                "skills": skills,
                "jd_text": _jd(arch, name, city, seniority, (lo, hi)),
            }
        )
    return jobs
